// Purpose: Keeps the ABI consumed by workspace applications identical to the compiled contract.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const artifactPath = resolve(
    packageRoot,
    "artifacts/contracts/ReferralProgram.sol/ReferralProgram.json",
);
const outputPath = resolve(packageRoot, "index.ts");

const artifact = JSON.parse(await readFile(artifactPath, "utf8"));
const source = `// This file is generated by scripts/generate-abi.js after compiling ReferralProgram.sol.
// It exposes the contract ABI for consumption by other workspace packages.

import type { Abi } from "viem";

export const RefferalABI = ${JSON.stringify(artifact.abi, null, 2)} as const satisfies Abi;
`;

await writeFile(outputPath, source);
